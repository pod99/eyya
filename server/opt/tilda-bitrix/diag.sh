#!/bin/bash
echo "=========================================="
echo "  TILDA-BITRIX WEBHOOK — DIAGNOSTICS"
echo "=========================================="
echo ""
echo "--- Docker ---"
docker ps -a --filter name=tilda-bitrix --format "table {{.Names}}\t{{.Status}}\t{{.Ports}}"
echo ""
echo "--- Health ---"
curl -s http://127.0.0.1:8000/health 2>/dev/null || echo "APP NOT REACHABLE"
echo ""
echo ""
echo "--- App logs (last 30) ---"
docker logs tilda-bitrix-app-1 --tail 30 2>&1
echo ""
echo "--- Requests summary ---"
docker exec tilda-bitrix-db-1 psql -U tilda -d tilda_bitrix -t -c "SELECT status, count(*) FROM tilda_requests GROUP BY status ORDER BY count DESC"
echo ""
echo "--- Last 10 requests ---"
docker exec tilda-bitrix-db-1 psql -U tilda -d tilda_bitrix -c "SELECT id, tilda_order_id, phone, status, bitrix_entity_id, substring(error for 60) as error FROM tilda_requests ORDER BY id DESC LIMIT 10"
echo ""
echo "--- Last 15 integration logs ---"
docker exec tilda-bitrix-db-1 psql -U tilda -d tilda_bitrix -c "SELECT id, request_id, action, rest_method, status, substring(error for 60) as error FROM integration_logs ORDER BY id DESC LIMIT 15"
echo ""
echo "--- Retry queue ---"
docker exec tilda-bitrix-db-1 psql -U tilda -d tilda_bitrix -c "SELECT id, request_id, retry_count, status, substring(last_error for 60) as last_error, next_retry_at FROM retry_queue WHERE status != '''done''' ORDER BY id DESC LIMIT 5"
echo ""
echo "--- Errors (requests) ---"
docker exec tilda-bitrix-db-1 psql -U tilda -d tilda_bitrix -c "SELECT id, tilda_order_id, status, substring(error for 80) as error FROM tilda_requests WHERE error IS NOT NULL AND error != '''''' AND status NOT IN ('''created''', '''updated''') ORDER BY id DESC LIMIT 10"
echo ""
echo "--- Bitrix config ---"
grep -E 'BITRIX_WEBHOOK_URL|RESPONSIBLE_USER_ID' /opt/tilda-bitrix/.env | sed 's/=.*/=***/'
echo ""
echo "=========================================="
